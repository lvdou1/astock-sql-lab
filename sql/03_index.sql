-- ============================================================
-- 03_index.sql  索引
-- 建在装载之后：先灌数据再建索引，比边灌边维护快得多
-- ============================================================

-- 事实表的主键已经是 (stock_code, trade_date)，DuckDB 会为它建索引。
-- 补充一条常用的访问路径：按日期切片（比如"看某一天的横截面"）。
CREATE INDEX IF NOT EXISTS idx_quote_date ON fact_daily_quote (trade_date);

-- 财务表按报告期筛选（"看所有股票 2026Q3 的情况"）
CREATE INDEX IF NOT EXISTS idx_fin_report_date ON fact_financial (report_date);

-- 实测：本项目数据量只有 2.6 万行，索引带来的提升可以忽略。
-- 在百万行级别（比如全市场 5000 只股票 × 10 年）差距才会显现，
-- 原因不是"加了索引就快"，而是索引让数据库不必全表扫描。
-- 复现方式：注释掉本文件对比 run.py 的耗时。
